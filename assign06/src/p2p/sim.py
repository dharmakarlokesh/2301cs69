"""Five-node localhost experiment: discovery, relay, partition, reconnection, convergence,
and adversarial input. Produces reports/experiment.md and reports/logs/*.jsonl."""

from __future__ import annotations

import asyncio
import json
import os
import random
import struct
import time

from chain.block import Block, target_from_bits
from chain.chain import ChainParams, make_genesis
from chain.crypto import Key
from chain.tx import OutPoint, TxOut, sign_tx

from .node import Node, NodeConfig
from .protocol import MAGIC, MAX_MESSAGE_SIZE, encode

ALICE, BOB, CAROL, DAVE, ERIN = (Key.from_seed(n) for n in ("alice", "bob", "carol", "dave", "erin"))
MINERS = [Key.from_seed(f"miner{i}") for i in range(5)]


async def wait_for(cond, timeout=15.0, what="condition"):
    t0 = time.monotonic()
    while time.monotonic() - t0 < timeout:
        if cond():
            return time.monotonic() - t0
        await asyncio.sleep(0.05)
    raise TimeoutError(f"timed out waiting for {what}")


def tips(nodes):
    return [n.chain.tip.block.hash.hex()[:10] for n in nodes]


def converged(nodes):
    return len({n.chain.tip.block.hash for n in nodes}) == 1


async def make_network(n=5, log_dir=None, seed=7, latency=(0.02, 0.08), target_bits=12, **cfg_kw):
    random.seed(seed)
    params = ChainParams(pow_limit=target_from_bits(4))
    genesis = make_genesis(params, ALICE.pkh, int(time.time()) - 3600, target_from_bits(8))
    nodes = []
    for i in range(n):
        cfg = NodeConfig(latency=random.uniform(*latency), jitter=0.01,
                         block_target=target_from_bits(target_bits), **cfg_kw)
        node = Node(f"node{i}", params, genesis, cfg,
                    log_path=os.path.join(log_dir, f"node{i}.jsonl") if log_dir else None,
                    miner_pkh=MINERS[i].pkh)
        await node.start()
        nodes.append(node)
    for node in nodes[1:]:                             # everyone only knows the seed node0
        node.add_known(nodes[0].id, *nodes[0].addr)
    return nodes, genesis


async def full_mesh(nodes, timeout=15.0):
    return await wait_for(lambda: all(len(n.connected_ids()) == len(nodes) - 1 for n in nodes),
                          timeout, "full mesh")


class Attacker:
    """Raw TCP client used to send malformed or abusive traffic."""

    def __init__(self, host, port):
        self.host, self.port = host, port

    async def __aenter__(self):
        self.r, self.w = await asyncio.open_connection(self.host, self.port)
        return self

    async def __aexit__(self, *a):
        self.w.close()

    async def send_raw(self, b: bytes):
        self.w.write(b)
        await self.w.drain()

    async def hello(self, node_id="mallory"):
        await self.send_raw(encode({"type": "hello", "node_id": node_id, "listen_port": 1,
                                    "height": 0, "tip": "00" * 32}))

    async def closed_by_peer(self, timeout=5.0) -> bool:
        try:
            while True:
                data = await asyncio.wait_for(self.r.read(65536), timeout)
                if not data:
                    return True
        except (asyncio.TimeoutError, ConnectionError):
            return False


def frame(payload: bytes) -> bytes:
    return MAGIC + struct.pack(">I", len(payload)) + payload


async def run_experiment(out_dir: str = "reports") -> str:
    log_dir = os.path.join(out_dir, "logs")
    os.makedirs(log_dir, exist_ok=True)
    for f in os.listdir(log_dir):
        os.remove(os.path.join(log_dir, f))
    nodes, genesis = await make_network(log_dir=log_dir)
    n0, n1, n2, n3, n4 = nodes
    out = ["# Assignment 6 — experiment report", "",
           "Generated by `python -m p2p experiment`: 5 nodes on localhost TCP, each with 20–80 ms of "
           "artificial latency plus jitter. Structured logs (one JSON object per line with `ts`, "
           "`node`, `peer`, `object`, `event`) are in `reports/logs/node*.jsonl`.", ""]

    def step(title):
        out.extend(["", f"## {title}", ""])

    def say(s):
        out.append(f"- {s}")

    try:
        step("1. Peer discovery")
        t = await full_mesh(nodes)
        say(f"Nodes 1–4 were only told about the seed `node0`. Through `getaddr`/`addr` every node "
            f"discovered the others and the network became a **full mesh** (each node has 4 peers) "
            f"in {t:.2f}s.")

        step("2. Transaction and block relay (inventory first)")
        for _ in range(3):
            await n0.mine(ALICE.pkh)
        await wait_for(lambda: converged(nodes) and n4.chain.height == 3, what="initial sync")
        say(f"node0 mined 3 blocks paying Alice; all nodes are at height 3 (tips {set(tips(nodes))}).")
        coins = sorted(op for op, o in n0.chain.utxo.utxos.items() if o.pubkey_hash == ALICE.pkh)
        c = coins
        tx0 = sign_tx([(c[0], ALICE)], [TxOut(20, BOB.pkh), TxOut(29, ALICE.pkh)])
        await n3.submit_local_tx(tx0)
        await wait_for(lambda: all(tx0.txid() in n.mempool for n in nodes), what="tx relay")
        say(f"Alice's payment `{tx0.txid().hex()[:12]}` was submitted to node3 and reached every "
            f"mempool via `inv` → `getdata` → `tx`.")
        await n1.mine()
        await wait_for(lambda: converged(nodes) and all(len(n.mempool) == 0 for n in nodes), what="block relay")
        say(f"node1 mined it into block `{n1.chain.tip.block.short()}`; every node connected the block and "
            "removed the tx from its mempool.")
        inv_first = [e for e in n2.events if e["event"] in ("recv-inv", "recv-block")
                     and n1.chain.tip.block.hash.hex()[:12] in (e["object"] or "")]
        say("Relay order seen at node2 for that block: " +
            " → ".join(f"`{e['event']}` from {e['peer']}" for e in inv_first[:3]) +
            ". The full block is only sent after the peer asks for it.")

        step("3. Partition into {node0,node1} and {node2,node3,node4}")
        g1, g2 = nodes[:2], nodes[2:]
        for a in g1:
            await a.block_peers({b.id for b in g2})
        for b in g2:
            await b.block_peers({a.id for a in g1})
        await asyncio.sleep(0.3)
        say(f"Cross-group connections closed. Peers: " +
            ", ".join(f"{n.id}={sorted(n.connected_ids())}" for n in nodes))
        tx_x = sign_tx([(c[1], ALICE)], [TxOut(30, CAROL.pkh), TxOut(19, ALICE.pkh)])   # only side X
        tx_conf = sign_tx([(c[2], ALICE)], [TxOut(40, DAVE.pkh), TxOut(9, ALICE.pkh)])  # double spend...
        tx_y = sign_tx([(c[2], ALICE)], [TxOut(45, ERIN.pkh), TxOut(3, ALICE.pkh)])     # ...of the same coin
        await n0.submit_local_tx(tx_x)
        await n1.submit_local_tx(tx_conf)
        await n3.submit_local_tx(tx_y)
        await wait_for(lambda: all(len(n.mempool) == 2 for n in g1) and all(len(n.mempool) == 1 for n in g2),
                       what="partitioned mempools")
        say(f"Side X mempools: tx_x `{tx_x.txid().hex()[:12]}` (Alice→Carol) and tx_conf "
            f"`{tx_conf.txid().hex()[:12]}` (Alice→Dave, coin #3). Side Y mempools: tx_y "
            f"`{tx_y.txid().hex()[:12]}` (Alice→Erin, **the same coin #3**).")
        bx = await n1.mine()
        by1 = await n2.mine()
        await wait_for(lambda: all(n.chain.tip.block.hash == bx.hash for n in g1)
                       and all(n.chain.tip.block.hash == by1.hash for n in g2), what="one block each side")
        say(f"One block mined on each side: X1 `{bx.short()}` (contains tx_x and tx_conf) and "
            f"Y1 `{by1.short()}` (contains tx_y). Equal height, so the network **disagrees**: tips = "
            f"{tips(nodes)}")
        by2 = await n4.mine()
        await wait_for(lambda: all(n.chain.tip.block.hash == by2.hash for n in g2), what="Y2")
        say(f"An additional block Y2 `{by2.short()}` is mined on side Y, which now has more work.")

        step("4. Heal the partition: reconnection and convergence")
        t_heal = time.monotonic()
        for n in nodes:
            n.unblock_all()
        await full_mesh(nodes)
        t_mesh = time.monotonic() - t_heal
        await wait_for(lambda: converged(nodes), what="convergence")
        t_conv = time.monotonic() - t_heal
        await wait_for(lambda: all(tx_x.txid() in n.mempool for n in nodes), what="tx_x re-relayed")
        say(f"Connections re-established in {t_mesh:.2f}s; all nodes converged on Y2 `{by2.short()}` in "
            f"{t_conv:.2f}s (tips {set(tips(nodes))}).")
        for n in g1:
            reorg = [e for e in n.events if e["event"] == "reorg"][-1]
            recon = [e for e in n.events if e["event"] == "tx-reconsidered"]
            say(f"{n.id} reorganised: disconnected {reorg['disconnected']}, connected "
                f"{reorg['connected']}. Stale-block txs reconsidered: " +
                ", ".join(f"`{e['object']}` → **{e['result']}** ({e['reason']})" for e in recon))
        say(f"tx_x (still valid) is back in **every** mempool, re-announced to side Y. tx_conf "
            f"conflicts with tx_y, which is already in the chain, so it was dropped. "
            f"Mempools: {[len(n.mempool) for n in nodes]}")
        await n3.mine()
        await wait_for(lambda: converged(nodes) and all(len(n.mempool) == 0 for n in nodes), what="final")
        hashes = {n.chain.utxo.state_hash() for n in nodes}
        assert len(hashes) == 1
        say(f"node3 mined tx_x into a new block. Final: height {n0.chain.height} on every node, identical "
            f"UTXO state hash `{hashes.pop()[:16]}…`, all mempools empty. Erin has "
            f"{n0.chain.utxo.balance(ERIN.pkh)} (tx_y won), Dave has {n0.chain.utxo.balance(DAVE.pkh)}, "
            f"Carol has {n0.chain.utxo.balance(CAROL.pkh)}.")

        step("5. Remaining responsive under malformed or repeated input (attacks on node2)")
        rows = ["| Attack | Node reaction |", "|---|---|"]
        host, port = n2.addr
        async with Attacker(host, port) as a:
            await a.send_raw(b"GET / HTTP/1.1\r\n\r\n")
            rows.append(f"| Garbage bytes (bad magic) | disconnected immediately: {await a.closed_by_peer()} |")
        async with Attacker(host, port) as a:
            await a.send_raw(MAGIC + struct.pack(">I", MAX_MESSAGE_SIZE + 1))
            rows.append(f"| Frame declaring {MAX_MESSAGE_SIZE + 1} bytes (over 1 MiB limit) | "
                        f"disconnected before reading the body: {await a.closed_by_peer()} |")
        async with Attacker(host, port) as a:
            rows.append(f"| Connect and stay silent (no `hello`) | handshake timeout after "
                        f"{n2.cfg.handshake_timeout}s, disconnected: {await a.closed_by_peer(6)} |")
        async with Attacker(host, port) as a:
            await a.hello("mallory-json")
            for _ in range(12):
                await a.send_raw(frame(b"{not json"))
            closed = await a.closed_by_peer()
            rows.append(f"| 12 frames of invalid JSON | `error` replies, +10 score each, **banned** at 100: {closed} |")
        async with Attacker(host, port) as a:
            await a.hello("mallory-flood")
            burst = b"".join(encode({"type": "ping", "nonce": i}) for i in range(1500))
            await a.send_raw(burst)
            closed = await a.closed_by_peer()
            rows.append(f"| 1,500 pings in one burst (bucket {int(n2.cfg.burst)}, {int(n2.cfg.rate)}/s) | "
                        f"excess messages dropped, rate-limit penalties, banned: {closed} |")
        async with Attacker(host, port) as a:
            await a.hello("mallory-dup")
            await asyncio.sleep(0.2)
            inv = encode({"type": "inv", "items": [{"kind": "block", "id": n0.chain.tip.block.hash.hex()}]})
            await a.send_raw(inv * 50)
            await asyncio.sleep(0.5)
            reqs = [e for e in n2.events if e["peer"] == "mallory-dup" and e["event"] == "recv-inv"]
            rows.append(f"| 50 repeated `inv` for a block node2 already has | {len(reqs)} received, "
                        f"0 `getdata` sent (duplicate suppression) |")
        async with Attacker(host, port) as a:
            await a.hello("mallory-badblock")
            await asyncio.sleep(0.2)
            fake = n2.chain.tip.block.to_obj()
            fake["header"]["timestamp"] += 1
            while Block.from_obj(fake).header.pow_ok():            # make sure PoW is invalid
                fake["header"]["nonce"] += 1
            for _ in range(2):
                await a.send_raw(encode({"type": "block", "block": fake}))
            closed = await a.closed_by_peer()
            rows.append(f"| Block with invalid PoW, sent twice | rejected, +50 each, banned: {closed} |")
        out += rows
        tx_final = sign_tx([(c[3], ALICE)], [TxOut(10, BOB.pkh), TxOut(39, ALICE.pkh)])
        await n4.submit_local_tx(tx_final)
        await wait_for(lambda: tx_final.txid() in n2.mempool, what="post-attack relay")
        await n2.mine()
        await wait_for(lambda: converged(nodes) and all(len(n.mempool) == 0 for n in nodes), what="post-attack")
        out += ["", f"- After the attacks node2 still relays and mines: a new tx from node4 reached it, node2 "
                    f"mined it, and all 5 nodes converged at height {n0.chain.height}. Bans held by node2: "
                    f"{sorted(n2.banned)}"]

        step("6. Structured log sample (node0, around the reorg)")
        reorg_idx = next(i for i, e in enumerate(n0.events) if e["event"] == "reorg")
        sample = n0.events[max(0, reorg_idx - 6): reorg_idx + 4]
        out += ["```json", *[json.dumps(e) for e in sample], "```"]
        counts = {}
        for n in nodes:
            for e in n.events:
                counts[e["event"]] = counts.get(e["event"], 0) + 1
        out += ["", "Event counts across all nodes:", "", "| event | count |", "|---|---:|",
                *[f"| {k} | {v} |" for k, v in sorted(counts.items(), key=lambda kv: -kv[1])]]
    finally:
        for n in nodes:
            await n.stop()
    report = "\n".join(out) + "\n"
    with open(os.path.join(out_dir, "experiment.md"), "w") as f:
        f.write(report)
    return report
